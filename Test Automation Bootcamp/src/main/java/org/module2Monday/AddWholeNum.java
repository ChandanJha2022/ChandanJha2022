package org.module2Monday;

public class AddWholeNum {
    static void main() {
        int wholenumsum =0;
        for (int i = 50; i <= 100; i++) {
            wholenumsum = wholenumsum + i;
        }
        System.out.println("Sum of all whole numbers from 50 to 100 is : " + wholenumsum);
    }
}
